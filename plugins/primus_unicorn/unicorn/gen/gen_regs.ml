(* Generates the tables of the register names of Unicorn.

   usage: gen_regs.exe <include-dir> <arch>:<header>:<prefix> ...

   For each architecture, collects the enumeration constants that start
   with the prefix, e.g., UC_X86_REG_, from the header and prints a C
   table of their names, without the prefix, and values. The values are
   left to the C compiler, as some constants are aliases. *)

let is_ident c =
  match c with 'A' .. 'Z' | 'a' .. 'z' | '0' .. '9' | '_' -> true | _ -> false

let ident line pos =
  let len = String.length line in
  let rec stop i = if i < len && is_ident line.[i] then stop (i + 1) else i in
  String.sub line pos (stop pos - pos)

let starts_with ~prefix s =
  String.length s >= String.length prefix
  && String.sub s 0 (String.length prefix) = prefix

(* the markers of the ends of the enumerations, not registers *)
let is_marker name = name = "INVALID" || name = "ENDING"

let constants file prefix =
  let ic = open_in file in
  let rec loop acc =
    match input_line ic with
    | exception End_of_file ->
        close_in ic;
        List.rev acc
    | line ->
        let line = String.trim line in
        if starts_with ~prefix line then
          let id = ident line 0 in
          let name =
            String.sub id (String.length prefix)
              (String.length id - String.length prefix)
          in
          if is_marker name || List.mem id acc then loop acc
          else loop (id :: acc)
        else loop acc
  in
  loop []

let () =
  let dir = Sys.argv.(1) in
  let arches =
    Array.to_list (Array.sub Sys.argv 2 (Array.length Sys.argv - 2))
  in
  print_string "/* generated by gen_regs.exe, do not edit */\n\n";
  print_string "#include \"unicorn_regs.h\"\n\n";
  let arches =
    List.map
      (fun spec ->
        match String.split_on_char ':' spec with
        | [ arch; header; prefix ] ->
            let ids = constants (Filename.concat dir header) prefix in
            if ids = [] then failwith ("no registers in " ^ header);
            Printf.printf "static const struct bap_uc_reg %s_regs[] = {\n" arch;
            List.iter
              (fun id ->
                let name =
                  String.sub id (String.length prefix)
                    (String.length id - String.length prefix)
                in
                Printf.printf "    {\"%s\", %s},\n" name id)
              ids;
            print_string "    {0, 0}};\n\n";
            arch
        | _ -> failwith ("invalid specification " ^ spec))
      arches
  in
  print_string
    "const struct bap_uc_reg *bap_uc_reg_table(uc_arch arch) {\n\
    \    switch (arch) {\n";
  List.iter
    (fun arch ->
      Printf.printf "    case UC_ARCH_%s: return %s_regs;\n"
        (String.uppercase_ascii arch)
        arch)
    arches;
  print_string "    default: return 0;\n    }\n}\n"

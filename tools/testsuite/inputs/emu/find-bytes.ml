#require "bap-primus-native.emu"

open Core
open Bap.Std
open Bap_primus.Std
module Emu = Bap_emu

let data = 0x500000L
let generated = 0x502000L
let code = 0x503000L
let check name ok = if not ok then failwith name
let addresses hits = String.concat ~sep:" " (List.map hits ~f:(sprintf "%Lx"))

let find emu ?provenance name ~pattern ~ranges expected =
  let hits = Emu.find_bytes ?provenance emu ~pattern ~ranges in
  List.iter hits ~f:(fun addr ->
      check
        (sprintf "%s: hit at %Lx disagrees with Emu.read" name addr)
        (String.equal pattern (Emu.read emu addr (String.length pattern))));
  if not (List.equal Int64.equal expected hits) then
    failwithf "%s: expected %s, got %s" name (addresses expected)
      (addresses hits) ()

let allocate emu =
  Emu.primus emu
    (module functor
              (Machine : Primus.Machine.S)
              ->
              struct
                open Machine.Syntax
                module Memory = Primus.Memory.Make (Machine)

                let init () =
                  let addr = Word.of_int64 ~width:64 in
                  let region base size generator =
                    Memory.allocate (addr base) size ?generator
                  in
                  let filled byte =
                    Some (Primus.Generator.static ~width:8 byte)
                  in
                  region data 0x2000 (filled 0) >>= fun () ->
                  region generated 0x1000
                    (Some
                       (Primus.Generator.Random.lcg ~width:8 ~min:0x5a ~max:0x5a
                          0))
                  >>= fun () ->
                  region code 0x1000 (filled 0) >>= fun () ->
                  Memory.protect ~lower:(addr code)
                    ~upper:(addr Int64.(code + 0xfffL))
                    { readable = true; writable = true; executable = true }
              end)

let run file engine =
  let emu = Emu.create ~engine (Bap_script.project file) in
  allocate emu;
  check "the ELF header isn't mapped"
    (Poly.equal (Emu.provenance emu 0x400000L) Emu.Mapped);
  find emu "mapped ELF header" ~pattern:"\x7fELF"
    ~ranges:[ (0x400000L, 0x400fffL) ]
    [ 0x400000L ];

  let stored = Int64.(data + 0x40L) in
  Emu.write emu stored "stored-data";
  find emu "stored data" ~pattern:"stored-data"
    ~ranges:[ (stored, Int64.(stored + 10L)) ]
    [ stored ];

  let unaligned = Int64.(data + 3L) in
  Emu.write emu unaligned "unaligned";
  find emu "unaligned hit" ~pattern:"unaligned"
    ~ranges:[ (data, Int64.(data + 0x20L)) ]
    [ unaligned ];

  let overlap = Int64.(data + 0x100L) in
  Emu.write emu overlap "ABABA";
  find emu "overlapping hits" ~pattern:"ABA"
    ~ranges:[ (overlap, Int64.(overlap + 4L)) ]
    [ overlap; Int64.(overlap + 2L) ];

  let crossing = Int64.(data + 0xffdL) in
  let crossing_pattern = "PAGECROSS" in
  Emu.write emu crossing crossing_pattern;
  find emu "page-crossing hit" ~pattern:crossing_pattern
    ~ranges:
      [
        ( Int64.(crossing - 1L),
          Int64.(crossing + of_int (String.length crossing_pattern)) );
      ]
    [ crossing ];

  let first = Int64.(data + 0x200L) and second = Int64.(data + 0x300L) in
  Emu.write emu first "~";
  Emu.write emu second "~";
  find emu "adjacent inclusive ranges" ~pattern:"~"
    ~ranges:[ (first, first); (Int64.(first + 1L), second) ]
    [ first; second ];
  find emu "merged overlapping ranges" ~pattern:"~"
    ~ranges:[ (first, second); (first, second); (first, first) ]
    [ first; second ];

  let pending = Int64.(data + 0x1800L) in
  let pending_pattern = "S12store" in
  Emu.write emu code ("\x48\xb8" ^ pending_pattern ^ "\x48\x89\x07\xc3");
  (match Emu.call emu code ~args:[ pending ] with
  | Some _ -> ()
  | None -> failwith "the store writer didn't return");
  find emu "program pending store" ~pattern:pending_pattern
    ~ranges:[ (pending, Int64.(pending + 7L)) ]
    [ pending ];

  check "the generated fixture has the wrong provenance"
    (Poly.equal (Emu.provenance emu generated) Emu.Generated);
  find emu "unmaterialized generated bytes" ~provenance:[ Emu.Generated ]
    ~pattern:"Z"
    ~ranges:[ (generated, Int64.(generated + 3L)) ]
    [];
  check "the generated fixture didn't materialize as Z"
    (String.equal "ZZZZ" (Emu.read emu generated 4));
  find emu "generated bytes excluded by default" ~pattern:"Z"
    ~ranges:[ (generated, Int64.(generated + 3L)) ]
    [];
  find emu "materialized generated bytes" ~provenance:[ Emu.Generated ]
    ~pattern:"Z"
    ~ranges:[ (generated, Int64.(generated + 3L)) ]
    [
      generated;
      Int64.(generated + 1L);
      Int64.(generated + 2L);
      Int64.(generated + 3L);
    ];

  find emu "empty ranges" ~pattern:"\x7fELF" ~ranges:[] [];
  find emu "empty provenance" ~provenance:[] ~pattern:"\x7fELF"
    ~ranges:[ (0x400000L, 0x400fffL) ]
    [];
  (match Emu.find_bytes emu ~pattern:"" ~ranges:[ (0x400000L, 0x400fffL) ] with
  | exception Invalid_argument _ -> ()
  | _ -> failwith "empty pattern was accepted");

  Gc.full_major ();
  let before = Emu.footprint () in
  find emu "large sparse absent pattern" ~pattern:"not present in sparse memory"
    ~ranges:[ (data, Int64.(data + 0x4000000L)) ]
    [];
  let after = Emu.footprint () in
  let growth = after.top_heap - before.top_heap in
  if growth > 64 * 1024 * 1024 then
    failwithf "sparse search grew the OCaml heap by %d bytes" growth ()

let () =
  let file = List.hd_exn (Bap_script.args ()) in
  List.iter
    [ (`Unicorn, "unicorn"); (`Lifted, "lifted") ]
    ~f:(fun (engine, name) ->
      run file engine;
      printf "%s: find bytes ok\n" name)

#require "bap-primus-native.emu"

open Core
open Bap.Std
open Bap_primus.Std
module Emu = Bap_emu

let check name ok = if not ok then failwith name

let expect_call ?thread emu addr ~args ~expected =
  match Emu.call emu addr ~args ?thread with
  | Some value when Int64.equal value expected -> ()
  | Some value -> failwithf "call returned %Lx instead of %Lx" value expected ()
  | None -> failwith "call didn't return"

let byte emu addr = Char.to_int (Emu.read emu addr 1).[0]

let allocate emu ~code ~data ~generated =
  Emu.primus emu
    (module functor
              (Machine : Primus.Machine.S)
              ->
              struct
                open Machine.Syntax
                module Memory = Primus.Memory.Make (Machine)

                let init () =
                  let addr = Word.of_int64 ~width:64 in
                  let region base generator =
                    Memory.allocate (addr base) 0x1000 ?generator
                  in
                  region data (Some (Primus.Generator.static ~width:8 0))
                  >>= fun () ->
                  region code (Some (Primus.Generator.static ~width:8 0))
                  >>= fun () ->
                  region generated None >>= fun () ->
                  Memory.protect ~lower:(addr code)
                    ~upper:(addr Int64.(code + 0xfffL))
                    { readable = true; writable = true; executable = true }
              end)

let find_change changes addr before after =
  List.exists changes ~f:(fun (change : Emu.change) ->
      Int64.equal change.addr addr
      && Poly.equal change.before before
      && Poly.equal change.after after)

let has_write writes addr value =
  List.exists writes ~f:(fun (a, _, x) ->
      Int64.equal a addr && Int64.equal Int64.(x land 0xffL) value)

let run file dir engine =
  let project () = Bap_script.project file in
  let emu = Emu.create ~engine (project ()) in
  let main = List.Assoc.find_exn (Emu.symbols emu) ~equal:String.equal "main" in
  (match Emu.run emu ~until:main with
  | Emu.Paused -> ()
  | _ -> failwith "didn't reach main");
  let code = 0x500000L
  and data = 0x501000L
  and generated = 0x502000L
  and native = 0x405000L
  and threaded = 0x501002L
  and crashed = 0x501003L in
  allocate emu ~code ~data ~generated;
  (* mov byte [rdi], imm8; movzx eax, byte [rdi]; ret *)
  let writer value =
    Printf.sprintf "\xc6\x07%c\x0f\xb6\x07\xc3" (Char.of_int_exn value)
  in
  (* mov byte [rdi], 0xa5; mov rax, [0x10]; ret *)
  Emu.write emu code
    (writer 0x5a ^ "\xc6\x07\xa5\x48\xa1\x10\x00\x00\x00\x00\x00\x00\x00\xc3");
  let fault = Int64.(code + 7L) in
  let writes = ref [] and native_reads = ref [] in
  let observe_write emu addr size value =
    writes := (addr, size, value) :: !writes;
    if Int64.equal addr native then
      native_reads := Emu.read emu addr size :: !native_reads
  in
  Emu.on_write emu ~primus:true ~first:data
    ~last:Int64.(data + 0xfffL)
    observe_write;
  Emu.on_write emu ~primus:true ~first:native
    ~last:Int64.(native + 5L)
    observe_write;
  check "zero-filled memory starts at zero" (byte emu data = 0);
  let initial = Emu.snapshot emu in
  expect_call emu code ~args:[ data ] ~expected:0x5aL;
  check "executed load and live read disagree" (byte emu data = 0x5a);
  check "executed store wasn't observed" (has_write !writes data 0x5aL);
  let first = Emu.snapshot emu in
  expect_call emu code ~args:[ data ] ~expected:0x5aL;
  Emu.write emu code (writer 0xa5);
  expect_call emu code ~args:[ data ] ~expected:0xa5L;
  check "stored-to-stored provenance is missing"
    (find_change (Emu.changes emu first) data Emu.Stored Emu.Stored);
  Emu.restore emu first;
  check "snapshot restored a stale pending byte" (byte emu data = 0x5a);
  Emu.restore emu initial;
  check "snapshot didn't restore zero" (byte emu data = 0);
  Emu.write emu code (writer 0x5a);
  expect_call emu code ~args:[ data ] ~expected:0x5aL;

  let initial_generated = byte emu generated in
  check "fresh byte isn't generated"
    (Poly.equal (Emu.provenance emu generated) Emu.Generated);
  let before_generated = Emu.snapshot emu in
  Emu.write emu code (writer 0x5b);
  expect_call emu code ~args:[ generated ] ~expected:0x5bL;
  check "generated-to-stored provenance is missing"
    (find_change
       (Emu.changes emu before_generated)
       generated Emu.Generated Emu.Stored);
  Emu.restore emu before_generated;
  check "generated byte wasn't restored" (byte emu generated = initial_generated);
  Emu.write emu code (writer 0x5b);
  expect_call emu code ~args:[ generated ] ~expected:0x5bL;

  check "native destination isn't initially zero" (byte emu native = 0);
  (match Emu.run emu ~until:0x4004dcL with
  | Emu.Paused -> ()
  | _ -> failwith "didn't return from native memcpy");
  check "native helper and live read disagree" (byte emu native = 0xb8);
  check "native helper store wasn't observed" (has_write !writes native 0xb8L);
  check "native helper write hook read stale memory"
    (List.exists !native_reads ~f:(String.is_prefix ~prefix:"\xb8"));
  expect_call emu native ~args:[] ~expected:42L;

  Emu.write emu code (writer 0x5d);
  let tid = Emu.spawn_thread emu ~start:code ~arg:threaded in
  expect_call emu code ~thread:tid ~args:[ threaded ] ~expected:0x5dL;
  check "thread-local effective address read stale memory"
    (byte emu threaded = 0x5d);
  check "thread store wasn't observed" (has_write !writes threaded 0x5dL);

  Emu.write emu code (writer 0xa5);
  Emu.set_reg emu "RDI" crashed;
  Emu.set_pc emu fault;
  (match Emu.run emu with
  | Emu.Failed _ -> ()
  | _ -> failwith "the crash routine didn't fault");
  check "failed-state read is stale" (byte emu crashed = 0xa5);
  let checkpoint = Filename.concat dir "memory-sync.ckpt" in
  Emu.save emu checkpoint;
  for round = 1 to 2 do
    let restored = Emu.create ~engine ~restore:checkpoint (project ()) in
    check
      (sprintf "fresh restore %d lost the pending crash store" round)
      (byte restored crashed = 0xa5);
    (match Emu.run restored with
    | Emu.Failed _ -> ()
    | _ -> failwithf "restored crash %d didn't fault again" round ());
    (match Emu.failure restored with
    | Some failure ->
        check "restored fault has the wrong pc"
          (Int64.equal failure.pc Int64.(fault + 3L));
        check "restored fault has the wrong address"
          (Int64.equal failure.addr 0x10L)
    | None -> failwith "restored crash has no structured fault");
    check
      (sprintf "failed-state read after restore %d is stale" round)
      (byte restored crashed = 0xa5)
  done;

  let emu = Emu.create ~engine (project ()) in
  (match Emu.run emu ~until:main with
  | Emu.Paused -> ()
  | _ -> failwith "didn't reach main for the failed call");
  allocate emu ~code ~data ~generated;
  (* mov byte [rsp-1], 0xa5; movzx eax, byte [rsp-1];
     mov rax, [0x10]; ret *)
  Emu.write emu code
    "\xc6\x44\x24\xff\xa5\x0f\xb6\x44\x24\xff\x48\xa1\x10\x00\x00\x00\x00\x00\x00\x00\xc3";
  let stack_fault = Int64.(code + 10L) in
  let outer_pc = Emu.pc emu and outer_sp = Emu.reg emu "RSP" in
  let tid = Emu.spawn_thread emu ~start:code ~arg:data in
  let stack_reads = ref [] in
  (match
     Emu.scoped emu (fun () ->
         Emu.on_read emu (fun emu addr size ->
             stack_reads := (addr, Emu.read emu addr size) :: !stack_reads);
         Emu.call emu code ~thread:tid)
   with
  | exception Failure _ -> ()
  | _ -> failwith "the stack-local routine didn't fail");
  let stack = Option.value_exn (Emu.execution_stats emu).stack in
  let local = Int64.(stack.lowest_sp - 1L) in
  check "failed call didn't restore the outer pc" Int64.(Emu.pc emu = outer_pc);
  check "failed call didn't restore the outer stack"
    Int64.(Emu.reg emu "RSP" = outer_sp);
  check "thread-local stack address is outside the call stack"
    Int64.(local >= stack.lower && local < stack.upper);
  check "failed call lost its temporary stack byte" (byte emu local = 0xa5);
  check "executed stack-local load saw a different value"
    (List.exists !stack_reads ~f:(fun (addr, data) ->
         Int64.equal addr local && String.equal data "\xa5"));
  (match Emu.failure emu with
  | Some failure ->
      check "failed call has the wrong pc" Int64.(failure.pc = stack_fault)
  | None -> failwith "failed call has no structured fault");
  Emu.set_reg emu "RSP" stack.lowest_sp;
  Emu.set_pc emu stack_fault;
  (match Emu.run emu with
  | Emu.Failed _ -> ()
  | _ -> failwith "the stack-local crash didn't fault");
  check "failed crash read lost the temporary stack byte" (byte emu local = 0xa5);
  let call_checkpoint = Filename.concat dir "failed-call-stack.ckpt" in
  Emu.save emu call_checkpoint;
  for round = 1 to 2 do
    let restored = Emu.create ~engine ~restore:call_checkpoint (project ()) in
    check
      (sprintf "fresh restore %d lost the failed call stack" round)
      (byte restored local = 0xa5);
    (match Emu.run restored with
    | Emu.Failed _ -> ()
    | _ -> failwithf "restored call crash %d didn't fault again" round ());
    (match Emu.failure restored with
    | Some failure ->
        check "restored call fault has the wrong pc"
          Int64.(failure.pc = stack_fault);
        check "restored call fault has the wrong address"
          Int64.(failure.addr = 0x10L)
    | None -> failwith "restored call crash has no structured fault");
    check
      (sprintf "failed call stack read after restore %d is stale" round)
      (byte restored local = 0xa5)
  done

let () =
  match Bap_script.args () with
  | [ file; dir; name ] ->
      let engine = if String.equal name "unicorn" then `Unicorn else `Lifted in
      run file dir engine;
      printf "%s: memory synchronization ok\n" name
  | _ -> failwith "expected REWRITE DIR ENGINE"

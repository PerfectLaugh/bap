(* Checks the bulk operations of the Primus memory against the
   operations on the bytes. *)

open Core
open Bap_core_theory
open Bap.Std
open Bap_primus.Std
open Monads.Std

module Machine = struct
  type 'a m = 'a

  include Primus.Machine.Make (Monad.Ident)
end

open Machine.Syntax
module Memory = Primus.Memory.Make (Machine)
module Value = Primus.Value.Make (Machine)

let addr x = Word.of_int ~width:32 x
let byte x = Word.of_int ~width:8 x

(* a target with the 32-bit addresses of bytes *)
let target =
  Theory.Target.declare ~package:"bap-test" "memory-test-32" ~bits:32
    ~data:
      (Theory.Var.define
         (Theory.Mem.define (Theory.Bitv.define 32) (Theory.Bitv.define 8))
         "mem")

let run start =
  let module System = Primus.System.Generic (Machine) in
  let system = Primus.System.define "memory-test" ~package:"bap-test" in
  match System.run ~start system (Project.empty target) with
  | Primus.Normal, _ -> ()
  | Primus.Exn exn, _ ->
      failwithf "the machine failed: %s" (Primus.Exn.to_string exn) ()

let check name ok = if not ok then failwithf "%s" name ()

let show (bytes : (char * Primus.Memory.protection) option array) =
  Array.to_list bytes
  |> List.map ~f:(function
    | None -> "_"
    | Some (c, (p : Primus.Memory.protection)) ->
        sprintf "%02x%s%s" (Char.to_int c)
          (if p.readable then "r" else "-")
          (if p.writable then "w" else "-"))
  |> String.concat ~sep:" "

(* the bytes from 0x0FFE to 0x1005: two unmapped bytes, then a region of
   four bytes, the first two of which are stored, the next one is
   generated, and the last one is not readable, then two unmapped bytes *)
let load () =
  run
    ( Memory.allocate (addr 0x1000) 4
        ~generator:(Primus.Generator.static ~width:8 0x55)
    >>= fun () ->
      Memory.store_bytes (addr 0x1000) "\x01\x02" >>= fun () ->
      Memory.protect ~lower:(addr 0x1003) ~upper:(addr 0x1003)
        { readable = false; writable = false; executable = false }
      >>= fun () ->
      Memory.load_bytes (addr 0x0FFE) 8 >>= fun bytes ->
      let expected = "_ _ 01rw 02rw 55rw 00-- _ _" in
      check
        (sprintf "load_bytes: expected %s, got %s" expected (show bytes))
        (String.equal (show bytes) expected);
      (* the generated byte is remembered, as load does *)
      Memory.load (addr 0x1002) >>| fun x ->
      check "the generated byte is remembered" (Word.equal x (byte 0x55)) )

(* the stored bytes are those that store_never_fail stores, also where
   nothing is mapped *)
let store () =
  run
    ( Memory.store_bytes (addr 0x2000) "abc" >>= fun () ->
      Machine.List.map [ 0; 1; 2 ] ~f:(fun i -> Memory.load (addr (0x2000 + i)))
      >>= fun xs ->
      check "store_bytes stores the bytes"
        (List.equal Word.equal xs [ byte 0x61; byte 0x62; byte 0x63 ]);
      Memory.is_mapped (addr 0x2003) >>| fun mapped ->
      check "store_bytes stores only its bytes" (not mapped) )

let check_string name expected actual =
  check
    (sprintf "%s: expected %S, got %S" name expected actual)
    (String.equal expected actual)

let string_of_loaded bytes =
  String.init (Array.length bytes) ~f:(fun i ->
      fst (Option.value_exn bytes.(i)))

let expected_words base data =
  List.init (String.length data) ~f:(fun i ->
      (addr (base + i), byte (Char.to_int data.[i])))

let check_words name expected actual =
  check name
    (List.equal
       (fun (a, x) (b, y) -> Word.equal a b && Word.equal x y)
       expected actual)

let page_crossing () =
  let base = 0x2FFC and data = "\x00\x01\x02\x03\x04\x05\x06\x07\x08\x09" in
  run
    ( Memory.store_bytes (addr base) data >>= fun () ->
      Memory.peek (addr base) (String.length data) >>= fun peeked ->
      check_string "page-crossing peek" data peeked;
      Memory.load_bytes (addr base) (String.length data) >>= fun loaded ->
      check_string "page-crossing load_bytes" data (string_of_loaded loaded);
      Machine.current () >>= fun self ->
      Memory.stored_count_of self >>= fun count ->
      check "page-crossing stored count" (count = String.length data);
      Memory.values_of self >>| fun values ->
      check_words "page-crossing values_of" (expected_words base data) values )

let scalar_values () =
  let base = 0x4000 in
  run
    ( Memory.store_bytes (addr base) "abc" >>= fun () ->
      Memory.get (addr base) >>= fun first ->
      Memory.load_bytes (addr base) 3 >>= fun _ ->
      Memory.get (addr base) >>= fun second ->
      check "scalar reads have a stable identity" (phys_equal first second);
      Value.of_int ~width:8 0x7A >>= fun replacement ->
      Memory.set (addr base) replacement >>= fun () ->
      Memory.get (addr base) >>= fun stored ->
      check "scalar overwrite preserves the written identity"
        (phys_equal replacement stored);
      Memory.store_bytes (addr base) "z" >>= fun () ->
      Memory.get (addr base) >>= fun bulk ->
      check "bulk overwrite replaces a scalar identity"
        ((not (phys_equal replacement bulk))
        && Word.equal (Primus.Value.to_word bulk) (byte 0x7A));
      Memory.del (addr base) >>= fun () ->
      Memory.is_mapped (addr base) >>= fun mapped ->
      check "delete removes a page byte" (not mapped);
      Memory.peek (addr base) 3 >>= fun remaining ->
      check_string "delete preserves the other page bytes" "\x00bc" remaining;
      Memory.values >>= fun values ->
      Memory.values >>| fun again ->
      let identities = List.map values ~f:(fun (_, _, value) -> value) in
      let identities' = List.map again ~f:(fun (_, _, value) -> value) in
      check "values materializes stable identities"
        (List.equal phys_equal identities identities') )

let snapshot_roundtrip () =
  let base = 0x5FFE and data = "abcdef" in
  run
    ( Memory.store_bytes (addr base) data >>= fun () ->
      Memory.get (addr (base + 2)) >>= fun _ ->
      Memory.snapshot >>= fun snapshot ->
      check_words "snapshot flattens pages and values"
        (expected_words base data)
        (Primus.Memory.Snapshot.values snapshot);
      Memory.store_bytes (addr base) "XXXXXX" >>= fun () ->
      Memory.restore snapshot >>= fun () ->
      Memory.peek (addr base) (String.length data) >>| fun restored ->
      check_string "snapshot restores flattened pages" data restored )

let copy_on_write () =
  let base = 0x6FFE and data = "\x10\x11\x12\x13" in
  let child_ran = ref false in
  run
    ( Memory.store_bytes (addr base) data >>= fun () ->
      Machine.current () >>= fun parent ->
      Machine.fork () >>= fun () ->
      Machine.current () >>= fun self ->
      if Monad.State.Multi.Id.equal self parent then (
        Memory.peek (addr base) (String.length data) >>= fun parent_data ->
        check_string "fork writes are isolated" data parent_data;
        Memory.get (addr base) >>= fun value ->
        check "fork promotion is isolated"
          (Word.equal (Primus.Value.to_word value) (byte 0x10));
        Machine.current () >>= fun self ->
        Memory.stored_count_of self >>| fun count ->
        check "fork deletion is isolated" (count = String.length data))
      else (
        child_ran := true;
        Memory.get (addr base) >>= fun _ ->
        Memory.store_bytes (addr (base + 1)) "\xAA\xBB" >>= fun () ->
        Memory.del (addr (base + 3)) >>= fun () -> Machine.switch parent) );
  check "the fork child executed" !child_ran

let region_clears_pages () =
  let base = 0x7000 in
  run
    ( Memory.store_bytes (addr base) "abcdef" >>= fun () ->
      Memory.get (addr (base + 2)) >>= fun _ ->
      Memory.add_region
        ~lower:(addr (base + 1))
        ~upper:(addr (base + 4))
        ~generator:(Primus.Generator.static ~width:8 0x55)
        ()
      >>= fun () ->
      Memory.peek (addr base) 6 >>= fun data ->
      check_string "new regions clear pages and values" "aUUUUf" data;
      Memory.origin (addr base) >>= fun before ->
      Memory.origin (addr (base + 2)) >>= fun inside ->
      check "region clearing preserves outside stores"
        (match before with Primus.Memory.Stored -> true | _ -> false);
      check "region clearing replaces inside stores"
        (match inside with Primus.Memory.Mapped -> true | _ -> false);
      Machine.current () >>= fun self ->
      Memory.stored_count_of self >>| fun count ->
      check "region clearing updates the logical count" (count = 2) )

let check_addrs name expected actual =
  check
    (sprintf "%s: expected %s, got %s" name
       (String.concat ~sep:", " (List.map expected ~f:Int.to_string))
       (String.concat ~sep:", "
          (List.map actual ~f:(fun a -> Int.to_string (Word.to_int_exn a)))))
    (List.equal Word.equal (List.map expected ~f:addr) actual)

let find_mapped_and_stored () =
  let base = 0x8000 in
  let mem =
    ok_exn
    @@ Bap.Std.Memory.create LittleEndian (addr base)
         (Bigstring.of_string "ABABA")
  in
  run
    ( Memory.map mem >>= fun () ->
      Memory.allocate
        (addr (base + 0x100))
        4
        ~generator:(Primus.Generator.static ~width:8 0x41)
      >>= fun () ->
      Memory.store_bytes (addr (base + 0x200)) "ABA" >>= fun () ->
      Memory.find_bytes ~pattern:"ABA"
        ~origins:[ Primus.Memory.Mapped; Primus.Memory.Stored ]
        ~ranges:
          [
            (addr (base + 3), addr (base + 4));
            (addr base, addr (base + 4));
            (addr base, addr (base + 2));
            (addr (base + 0x200), addr (base + 0x202));
          ]
      >>= fun hits ->
      check_addrs "merged ranges and unaligned hits"
        [ base; base + 2; base + 0x200 ]
        hits;
      Memory.find_bytes ~pattern:"AA" ~origins:[ Primus.Memory.Mapped ]
        ~ranges:[ (addr (base + 0x100), addr (base + 0x103)) ]
      >>= fun hits ->
      check_addrs "constant-fill hits"
        [ base + 0x100; base + 0x101; base + 0x102 ]
        hits;
      Memory.find_bytes ~pattern:"ABA" ~origins:[ Primus.Memory.Stored ]
        ~ranges:[ (addr base, addr (base + 4)) ]
      >>= fun hits ->
      check_addrs "origin filter" [] hits;
      Memory.find_bytes ~pattern:"ABA" ~origins:[]
        ~ranges:[ (addr base, addr (base + 4)) ]
      >>= fun hits ->
      check_addrs "empty origins" [] hits;
      Memory.find_bytes ~pattern:"ABA" ~origins:[ Primus.Memory.Mapped ]
        ~ranges:[]
      >>| fun hits -> check_addrs "empty ranges" [] hits )

let find_generated_only_materialized () =
  let base = 0x9000 in
  run
    ( Memory.allocate (addr base) 4 ~generator:(Primus.Generator.Random.byte 1)
    >>= fun () ->
      Machine.current () >>= fun self ->
      Memory.stored_count_of ~generated:true self >>= fun before ->
      check "generated memory starts unmaterialized" (before = 0);
      Memory.find_bytes ~pattern:"\x00"
        ~origins:[ Primus.Memory.Generated ]
        ~ranges:[ (addr base, addr (base + 3)) ]
      >>= fun hits ->
      check_addrs "search does not generate" [] hits;
      Memory.stored_count_of ~generated:true self >>= fun after ->
      check "search leaves generated memory unmaterialized" (after = 0);
      Memory.load (addr base) >>= fun generated ->
      let pattern =
        String.of_char (Char.of_int_exn (Word.to_int_exn generated))
      in
      Memory.stored_count_of ~generated:true self >>= fun materialized ->
      check "one generated byte is materialized" (materialized = 1);
      Memory.find_bytes ~pattern
        ~origins:[ Primus.Memory.Generated ]
        ~ranges:[ (addr base, addr (base + 3)) ]
      >>= fun hits ->
      check_addrs "materialized generated byte is searchable" [ base ] hits;
      Memory.find_bytes ~pattern ~origins:[ Primus.Memory.Stored ]
        ~ranges:[ (addr base, addr (base + 3)) ]
      >>= fun hits ->
      check_addrs "generated origin must be requested" [] hits;
      Memory.stored_count_of ~generated:true self >>| fun after ->
      check "materialized search is nonexpanding" (after = 1) )

let find_readability_and_holes () =
  let base = 0xA000 in
  let mem =
    ok_exn
    @@ Bap.Std.Memory.create LittleEndian (addr base)
         (Bigstring.of_string "ABAB")
  in
  run
    ( Memory.map mem >>= fun () ->
      Memory.protect
        ~lower:(addr (base + 1))
        ~upper:(addr (base + 1))
        { readable = false; writable = false; executable = false }
      >>= fun () ->
      Memory.find_bytes ~pattern:"AB" ~origins:[ Primus.Memory.Mapped ]
        ~ranges:[ (addr base, addr (base + 3)) ]
      >>= fun hits ->
      check_addrs "every matched byte must be readable" [ base + 2 ] hits;
      Memory.store_bytes (addr (base + 0x100)) "A" >>= fun () ->
      Memory.store_bytes (addr (base + 0x102)) "B" >>= fun () ->
      Memory.find_bytes ~pattern:"AB" ~origins:[ Primus.Memory.Stored ]
        ~ranges:[ (addr (base + 0x100), addr (base + 0x102)) ]
      >>| fun hits -> check_addrs "matches do not cross holes" [] hits )

let find_chunk_boundaries () =
  let base = 0xB000 in
  let data = Bytes.make 9000 '\x00' in
  Bytes.set data 4095 'X';
  Bytes.set data 4096 'Y';
  Bytes.set data 8191 'X';
  Bytes.set data 8192 'Y';
  run
    ( Memory.store_bytes (addr base) (Bytes.to_string data) >>= fun () ->
      Memory.find_bytes ~pattern:"XY" ~origins:[ Primus.Memory.Stored ]
        ~ranges:[ (addr base, addr (base + Bytes.length data - 1)) ]
      >>| fun hits ->
      check_addrs "patterns cross chunk overlaps"
        [ base + 4095; base + 8191 ]
        hits )

let find_pending_page_local () =
  let first = 0xCFFE and second = 0xD000 in
  let peeks = ref [] in
  let page addr = Word.to_int_exn addr land lnot 0xFFF in
  let backing : Primus.Memory.Backing.t =
    {
      memory = "mem";
      pending =
        (fun _ at ->
          List.exists [ first; second ] ~f:(fun pending ->
              page at = page (addr pending)));
      fetch = (fun _ _ -> failwith "find_bytes fetched pending bytes");
      fetch_all = (fun _ -> failwith "find_bytes fetched all pending bytes");
      peek =
        (fun _ base_addr ->
          let base = page base_addr in
          peeks := base :: !peeks;
          match base with
          | 0xC000 -> [ (addr first, "AB") ]
          | 0xD000 -> [ (addr second, "AB") ]
          | _ -> []);
      peek_all = (fun _ -> failwith "find_bytes called peek_all");
      stored = (fun _ _ _ -> ());
    }
  in
  run
    ( Memory.set_backing (Some backing) >>= fun () ->
      Machine.current () >>= fun self ->
      Memory.find_bytes ~pattern:"AB" ~origins:[ Primus.Memory.Stored ]
        ~ranges:[ (addr (first - 1), addr (second + 2)) ]
      >>= fun hits ->
      check_addrs "pending bytes overlay each page" [ first; second ] hits;
      check "backing peek is page-local"
        (List.equal Int.equal !peeks [ 0xD000; 0xC000 ]);
      Memory.stored_count_of self >>= fun count ->
      check "pending search does not store bytes" (count = 0);
      Memory.sparse_page_count_of self >>| fun pages ->
      check "pending search does not expand sparse pages" (pages = 0) )

let find_empty_pattern () =
  let raised =
    try
      ignore
        (Memory.find_bytes ~pattern:"" ~origins:[] ~ranges:[]
          : addr list Machine.t);
      false
    with Invalid_argument _ -> true
  in
  check "empty pattern is rejected" raised


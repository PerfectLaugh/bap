(* Checks the bulk operations of the Primus memory against the
   operations on the bytes. *)

open Core
open Bap_core_theory
open Bap.Std
open Bap_primus.Std
open Monads.Std

module Machine = struct
  type 'a m = 'a

  include Primus.Machine.Make (Monad.Ident)
end

open Machine.Syntax
module Memory = Primus.Memory.Make (Machine)

let addr x = Word.of_int ~width:32 x
let byte x = Word.of_int ~width:8 x

(* a target with the 32-bit addresses of bytes *)
let target =
  Theory.Target.declare ~package:"bap-test" "memory-test-32" ~bits:32
    ~data:
      (Theory.Var.define
         (Theory.Mem.define (Theory.Bitv.define 32) (Theory.Bitv.define 8))
         "mem")

let run start =
  let module System = Primus.System.Generic (Machine) in
  let system = Primus.System.define "memory-test" ~package:"bap-test" in
  match System.run ~start system (Project.empty target) with
  | Primus.Normal, _ -> ()
  | Primus.Exn exn, _ ->
      failwithf "the machine failed: %s" (Primus.Exn.to_string exn) ()

let check name ok = if not ok then failwithf "%s" name ()

let show (bytes : (char * Primus.Memory.protection) option array) =
  Array.to_list bytes
  |> List.map ~f:(function
    | None -> "_"
    | Some (c, (p : Primus.Memory.protection)) ->
        sprintf "%02x%s%s" (Char.to_int c)
          (if p.readable then "r" else "-")
          (if p.writable then "w" else "-"))
  |> String.concat ~sep:" "

(* the bytes from 0x0FFE to 0x1005: two unmapped bytes, then a region of
   four bytes, the first two of which are stored, the next one is
   generated, and the last one is not readable, then two unmapped bytes *)
let load () =
  run
    ( Memory.allocate (addr 0x1000) 4
        ~generator:(Primus.Generator.static ~width:8 0x55)
    >>= fun () ->
      Memory.store_bytes (addr 0x1000) "\x01\x02" >>= fun () ->
      Memory.protect ~lower:(addr 0x1003) ~upper:(addr 0x1003)
        { readable = false; writable = false; executable = false }
      >>= fun () ->
      Memory.load_bytes (addr 0x0FFE) 8 >>= fun bytes ->
      let expected = "_ _ 01rw 02rw 55rw 00-- _ _" in
      check
        (sprintf "load_bytes: expected %s, got %s" expected (show bytes))
        (String.equal (show bytes) expected);
      (* the generated byte is remembered, as load does *)
      Memory.load (addr 0x1002) >>| fun x ->
      check "the generated byte is remembered" (Word.equal x (byte 0x55)) )

(* the stored bytes are those that store_never_fail stores, also where
   nothing is mapped *)
let store () =
  run
    ( Memory.store_bytes (addr 0x2000) "abc" >>= fun () ->
      Machine.List.map [ 0; 1; 2 ] ~f:(fun i -> Memory.load (addr (0x2000 + i)))
      >>= fun xs ->
      check "store_bytes stores the bytes"
        (List.equal Word.equal xs [ byte 0x61; byte 0x62; byte 0x63 ]);
      Memory.is_mapped (addr 0x2003) >>| fun mapped ->
      check "store_bytes stores only its bytes" (not mapped) )

let () =
  load ();
  store ()

#!/bin/bash
# gen.sh SPEC MODULE-NAME: prints the OCaml tests for the cases in SPEC, one per
# line: mode | asm | init | expect, where init and expect are space-separated
# name=value pairs; lines starting with # are section comments
# the instructions are assembled with clang and llvm-objcopy of the Android NDK,
# NDK_BIN is its toolchains/llvm/prebuilt/<host>/bin directory
N=${NDK_BIN:?set NDK_BIN to the bin directory of the NDK toolchain}
W=$(mktemp -d)
spec=$1
echo "(* generated by gen/regenerate.sh from gen/$(basename $spec), do not edit *)"
echo
echo "open Arm_tests_helpers"
echo
echo "let suite ="
echo "  OUnit2.( >::: ) \"$2\""
echo "    ["
while IFS='|' read -r mode asm init expect; do
  mode=$(echo $mode); asm=$(echo "$asm" | sed 's/^ *//; s/ *$//')
  [ -z "$mode" ] && continue
  if [[ "$mode" == \#* ]]; then echo "      (* ${mode#\# } *)"; continue; fi
  case $mode in
    A64) t=aarch64-linux-android35; fl="" ;;
    A32) t=armv7a-linux-androideabi21; fl="-marm -mcpu=cortex-a15 -mfpu=vfpv4"; dir=.arm ;;
    T32) t=armv7a-linux-androideabi21; fl="-mthumb -mcpu=cortex-a15 -mfpu=vfpv4"; dir=.thumb ;;
  esac
  printf ".syntax unified\n.fpu vfpv4\n%s\n.text\n%s\n" "$dir" "$asm" > $W/a.s
  [ $mode = A64 ] && printf '.text\n%s\n' "$asm" > $W/a.s
  $N/clang --target=$t $fl -c $W/a.s -o $W/a.o 2> $W/err || { echo "ERROR assembling '$asm': $(cat $W/err)" >&2; exit 1; }
  $N/llvm-objcopy -O binary --only-section=.text $W/a.o $W/a.bin
  code=$(od -An -tx1 -v $W/a.bin | tr -s ' \n' ' ' | sed 's/^ //; s/ $//')
  pairs() { for p in $1; do printf '("%s", "%s"); ' "${p%%=*}" "${p#*=}"; done; }
  echo "      case $mode \"$asm\" \"$code\""
  echo "        ~init:[ $(pairs "$init")]"
  echo "        ~expect:[ $(pairs "$expect")];"
done < $spec
echo "    ]"
rm -rf $W

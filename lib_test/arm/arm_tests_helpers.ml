open Core
open Bap.Std

type mode = A64 | A32 | T32

let addr = 0x10000

(* the registers that are not variables of the targets *)
let typ name =
  let is prefix = String.is_prefix name ~prefix in
  if is "V" then Some (Type.imm 128)
  else if is "D" then Some (Type.imm 64)
  else if is "intrinsic:" then Some (Type.imm 64)
  else None

let a64 =
  Lifter_test.mode ~typ ~addr ~target:"armv8-a+le" ~encoding:"llvm-aarch64" ()

let a32 =
  Lifter_test.mode ~typ ~addr ~target:"armv7-a+fp+le" ~encoding:"llvm-armv7" ()

let t32 =
  Lifter_test.mode ~typ ~addr ~target:"armv7-a+fp+le" ~encoding:"llvm-thumb" ()

let mode = function A64 -> a64 | A32 -> a32 | T32 -> t32

let case m asm code ~init ~expect =
  Lifter_test.case (mode m) asm code [ (init, expect) ]

let lift m code = Lifter_test.lift (mode m) code

(* the mode of the tests generated by lib_test/cross/gen.sh, which puts
   the instructions at 0x20000 *)
let a32_qemu =
  Lifter_test.mode ~typ ~addr:0x20000 ~target:"armv7-a+fp+le"
    ~encoding:"llvm-armv7" ()

let t32_qemu =
  Lifter_test.mode ~typ ~addr:0x20000 ~target:"armv7-a+fp+le"
    ~encoding:"llvm-thumb" ()
